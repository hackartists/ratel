// Generates React icon components from packages/icons/resources/<group>/*.svg
// with the same markup packages/icons/build.rs emits for Dioxus:
//   <svg width height viewBox class xmlns> + the SVG's child elements verbatim
// (root width/height/fill are replaced by the component props, exactly like
// build.rs, so `[&>path]:stroke-*` utilities keep recoloring `stroke="black"`).
//
//   node apps/web/scripts/gen-icons.mjs files file
// writes apps/web/src/components/icons/<group>.tsx for each group.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const resources = resolve(here, "../../../packages/icons/resources");
const outDir = resolve(here, "../src/components/icons");

// SVG attribute (as build.rs writes it, kebab-case) -> React prop.
const PROPS = {
  "clip-path": "clipPath",
  "clip-rule": "clipRule",
  "fill-rule": "fillRule",
  "fill-opacity": "fillOpacity",
  "stroke-width": "strokeWidth",
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
  "stroke-opacity": "strokeOpacity",
  "stroke-miterlimit": "strokeMiterlimit",
  "stop-color": "stopColor",
  "stop-opacity": "stopOpacity",
};
const PLAIN = new Set(["d", "fill", "height", "id", "mask", "rx", "ry", "stroke", "transform", "width", "x", "y", "cx", "cy", "r", "points", "opacity", "offset"]);

function pascal(stem) {
  let name = stem;
  if (/^\d/.test(name)) {
    const rest = name.replace(/^\d+/, "");
    name = `icon${rest.replace(/^[-_]/, "")}`;
  }
  return name
    .split(/[-_ .]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("");
}

function camelToKebab(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

function jsxAttrs(raw) {
  const out = [];
  for (const m of raw.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)) {
    const kebab = camelToKebab(m[1]);
    const prop = PROPS[kebab] ?? (PLAIN.has(kebab) ? kebab : null);
    if (!prop) throw new Error(`unmapped SVG attribute: ${m[1]}`);
    if ((kebab === "id" || kebab === "class" || kebab === "xmlns") && m[2] === "") continue;
    out.push(`${prop}=${JSON.stringify(m[2])}`);
  }
  return out.length ? ` ${out.join(" ")}` : "";
}

function component(file) {
  const svg = readFileSync(file, "utf8");
  const root = svg.match(/<svg\b([^>]*)>/);
  const viewBox = root[1].match(/viewBox="([^"]*)"/)?.[1] ?? "0 0 24 24";
  const body = svg.slice(root.index + root[0].length, svg.lastIndexOf("</svg>"));
  const lines = [];
  let depth = 3;
  for (const m of body.matchAll(/<(\/?)([a-zA-Z]+)([^>]*?)(\/?)>/g)) {
    const [, closing, tag, attrs, selfClosing] = m;
    if (closing) {
      depth -= 1;
      lines.push(`${"  ".repeat(depth)}</${tag}>`);
    } else if (selfClosing) {
      lines.push(`${"  ".repeat(depth)}<${tag}${jsxAttrs(attrs)} />`);
    } else {
      lines.push(`${"  ".repeat(depth)}<${tag}${jsxAttrs(attrs)}>`);
      depth += 1;
    }
  }
  const name = pascal(basename(file, ".svg"));
  return `export function ${name}({ width = "24", height = "24", className = "" }: IconProps) {
  return (
    <svg width={width} height={height} viewBox=${JSON.stringify(viewBox)} className={className} xmlns="http://www.w3.org/2000/svg">
${lines.join("\n")}
    </svg>
  );
}
`;
}

for (const group of process.argv.slice(2)) {
  const dir = resolve(resources, group);
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".svg"))
    .sort()
    .map((f) => resolve(dir, f));
  const header = `// @generated by apps/web/scripts/gen-icons.mjs from packages/icons/resources/${group}.
// Same markup as packages/icons/src/icons/${group.replace(/-/g, "_")} (build.rs). Do not edit.
import type { IconProps } from "./validations";

`;
  const out = resolve(outDir, `${group}.tsx`);
  writeFileSync(out, header + files.map(component).join("\n"));
  console.log(`wrote ${out} (${files.length} icons)`);
}
