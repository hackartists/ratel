#!/usr/bin/env node
// Renders packages/ts-bridges/src/handlers/*.ts and the barrels from the
// handler manifests that `make gen-ts` writes to .gen/handlers/*.json (the
// ts_bridge tests emitted by the route macros, see
// packages/by-macros/src/server_fn/ts_bridge.rs), after ts-rs has exported
// the wire types to src/types/.
//
// Output follows biyard/asset's ts-bridges: one file per handler named after
// the Rust fn in camelCase, types imported from ../types (ts-rs), transport
// through ../runtime/client, and `bigint` normalized to `number` (the server
// sends i64 as JSON numbers). src/hooks is hand-maintained and never touched.
//
// Usage: node gen-handlers.mjs [--check]
//   --check  write nothing; exit 1 when handlers, barrels or types differ.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(pkg, "src");
const manifestDir = join(pkg, ".gen/handlers");
const handlersDir = join(src, "handlers");
const typesDir = join(src, "types");
const check = process.argv.includes("--check");

const HEADER = "// AUTO-GENERATED by `make gen-ts`. DO NOT EDIT.\n";
const RESERVED = new Set(
  "break case catch class const continue debugger default delete do else enum export extends false finally for function if import in instanceof new null return super switch this throw true try typeof var void while with yield let static implements interface package private protected public await".split(" "),
);

const camel = (s) => s.replace(/_+([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const param = (name) => (RESERVED.has(camel(name)) ? `${camel(name)}_` : camel(name));
const numbers = (ts) => ts.replace(/\bbigint\b/g, "number");
const stems = (dir) =>
  existsSync(dir)
    ? readdirSync(dir).filter((f) => f.endsWith(".ts") && f !== "index.ts").map((f) => f.slice(0, -3)).sort()
    : [];

if (!existsSync(manifestDir)) {
  console.error(`no manifests in ${manifestDir}; run \`make gen-ts\``);
  process.exit(1);
}
const manifests = readdirSync(manifestDir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((f) => JSON.parse(readFileSync(join(manifestDir, f), "utf8")));

// Export names: the Rust fn name in camelCase. Rust allows the same fn name in
// different modules; those get a method + route suffix so both stay usable.
const byName = new Map();
for (const m of manifests) byName.set(camel(m.name), [...(byName.get(camel(m.name)) ?? []), m]);
const renamed = [];
for (const [name, group] of byName) {
  for (const m of group) {
    if (group.length === 1) {
      m.exportName = name;
      continue;
    }
    const route = m.path
      .split("/")
      .filter((s) => s && !s.startsWith("{"))
      .map((s) => pascal(camel(s.replace(/-/g, "_"))))
      .join("");
    m.exportName = `${name}${pascal(m.method.toLowerCase())}${route}`;
    renamed.push(`${m.method} ${m.path}: ${m.name} → ${m.exportName}`);
  }
}

const outputs = new Map();
const missing = new Set();

for (const m of manifests) {
  const pathArgs = m.pathArgs.map((a) => ({ ...a, param: param(a.name) }));
  const query = m.queryArgs.map((a) => ({ ...a, param: param(a.name) }));
  // A GET "body" argument (a struct arg missing from the route's `?query`) is
  // never sent — the Rust client stub drops it too. Keep it in the signature
  // for parity, prefixed so the unused parameter doesn't fail type checks.
  const body = m.body ? { ...m.body, param: `${m.method === "GET" ? "_" : ""}${param(m.body.name)}` } : null;

  // Signature order: path args, required query args, body, optional query args.
  const sig = [
    ...pathArgs.map((a) => `${a.param}: ${numbers(a.ts)}`),
    ...query.filter((a) => !a.optional).map((a) => `${a.param}: ${numbers(a.ts)}`),
    ...(body ? [`${body.param}: ${numbers(body.ts)}`] : []),
    ...query.filter((a) => a.optional).map((a) => `${a.param}?: ${numbers(a.ts)}`),
  ];

  let path = m.path;
  for (const a of pathArgs) path = path.replace(`{${a.name}}`, `\${pathValue(${a.param})}`);

  const entry = (a) => (a.name === a.param ? a.name : `${a.name}: ${a.param}`);
  const queryObj = query.length ? `{ ${query.map(entry).join(", ")} }` : null;
  const bodyObj = body ? `{ ${entry(body)} }` : null;

  const fn = { GET: "apiGet", POST: "apiPost", PUT: "apiPut", PATCH: "apiPatch", DELETE: "apiDelete" }[m.method];
  const args =
    m.method === "GET"
      ? [queryObj]
      : m.method === "DELETE"
        ? [queryObj ?? (bodyObj ? "undefined" : null), bodyObj]
        : [bodyObj ?? (queryObj ? "undefined" : null), queryObj];
  while (args.length && args[args.length - 1] === null) args.pop();

  // ts-rs reports a default path for every named type, including ones that
  // aren't exported: string-mapped ids (`ts(type = "string")`, inlined as
  // `string`) and `ts(as = "…Wire")` models whose file lives under types/.
  // Import only names that actually occur in this handler's TS, from the
  // reported path when it exists, else from types/<name>.ts.
  const tsText = [m.returns, ...m.pathArgs.map((a) => a.ts), ...m.queryArgs.map((a) => a.ts), m.body?.ts ?? ""].join(" ");
  const used = new Set(tsText.match(/[A-Za-z_$][A-Za-z0-9_$]*/g) ?? []);
  const refs = m.refs
    .filter((r) => used.has(r.name))
    .map((r) => ({ name: r.name, path: existsSync(join(src, r.path)) ? r.path : `types/${r.name}.ts` }));
  for (const ref of refs) if (!existsSync(join(src, ref.path))) missing.add(ref.path);
  const returns = numbers(m.returns);
  const runtime = pathArgs.length ? ["apiX", "pathValue"] : ["apiX"];
  const imports = [
    ...refs.map((r) => `import type { ${r.name} } from "../${r.path.replace(/\.ts$/, "")}";`),
    `import { ${runtime.map((n) => (n === "apiX" ? fn : n)).sort().join(", ")} } from "../runtime/client";`,
  ];

  outputs.set(
    join(handlersDir, `${m.exportName}.ts`),
    `${HEADER}${imports.join("\n")}

/** \`${m.method} ${m.path}\` — Rust \`${m.name}\`. @throws ApiError */
export async function ${m.exportName}(${sig.join(", ")}): Promise<${returns}> {
  return ${fn}<${returns}>(${[`\`${path}\``, ...args].join(", ")});
}
`,
  );
}

const handlerNames = manifests.map((m) => m.exportName).sort();
const typeNames = stems(typesDir);

outputs.set(join(handlersDir, "index.ts"), HEADER + handlerNames.map((h) => `export { ${h} } from "./${h}";`).join("\n") + "\n");
outputs.set(join(typesDir, "index.ts"), HEADER + typeNames.map((t) => `export type { ${t} } from "./${t}";`).join("\n") + "\n");
outputs.set(
  join(src, "index.ts"),
  `${HEADER}
// Transport runtime (hand-written — owns fetch, the Tauri transport and errors).
export {
  apiGet,
  apiPost,
  apiPut,
  apiPatch,
  apiDelete,
  ApiError,
  isTauri,
  pathValue,
  setBaseUrl,
  setHeaderProvider,
} from "./runtime/client";
export type { ServerError } from "./runtime/client";

// Generated typed API: one fn per Rust #[get]/#[post]/... handler.
export * from "./handlers";
export * as api from "./handlers";

// Generated wire types (ts-rs).
export type * from "./types";
export * as types from "./types";
`,
);

// ts-rs output: bigint → number, trailing whitespace stripped.
for (const t of typeNames) {
  const file = join(typesDir, `${t}.ts`);
  const content = readFileSync(file, "utf8");
  outputs.set(file, numbers(content).replace(/[ \t]+$/gm, ""));
}

const drift = [];
for (const [file, content] of outputs) {
  const current = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (current !== content) drift.push(`${current === null ? "missing" : "changed"}: ${file}`);
}
const stale = existsSync(handlersDir)
  ? readdirSync(handlersDir).map((f) => join(handlersDir, f)).filter((f) => !outputs.has(f))
  : [];
drift.push(...stale.map((f) => `stale: ${f}`));

if (!check) {
  mkdirSync(handlersDir, { recursive: true });
  mkdirSync(typesDir, { recursive: true });
  for (const [file, content] of outputs) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== content) writeFileSync(file, content);
  }
  for (const f of stale) rmSync(f);
}

console.log(`handlers: ${manifests.length}  types: ${typeNames.length}  renamed (duplicate fn names): ${renamed.length}  missing type files: ${missing.size}`);
for (const r of renamed) console.log(`  renamed ${r}`);
for (const p of missing) console.log(`  missing ${p}`);
console.log(check ? `out of date: ${drift.length}` : `updated: ${drift.length}`);
process.exit((check && drift.length) || missing.size ? 1 : 0);
