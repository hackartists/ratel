#!/usr/bin/env node
// Generates packages/ts-bridges/src/handlers/*.ts and the src/index.ts barrel
// from the manifests the route macros write during `make gen-ts`
// (packages/by-macros/src/server_fn/ts_bridge.rs → .gen/handlers/*.json).
//
// Output follows biyard/asset's ts-bridges: one file per handler named after
// the Rust fn in camelCase, types imported from ../types/<Name> (ts-rs), and
// transport through ../runtime/client. src/hooks is hand-maintained and never
// touched here (see scaffold-ts-hooks.mjs).
//
// Usage: node gen-handlers.mjs [--check]
//   --check  write nothing; exit 1 when src/handlers or src/index.ts differ.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifestDir = join(pkg, ".gen/handlers");
const handlersDir = join(pkg, "src/handlers");
const typesDir = join(pkg, "src/types");
const check = process.argv.includes("--check");

const HEADER = "// AUTO-GENERATED by `make gen-ts` (packages/ts-bridges/scripts/gen-handlers.mjs). DO NOT EDIT.\n";
const RESERVED = new Set(
  "break case catch class const continue debugger default delete do else enum export extends false finally for function if import in instanceof new null return super switch this throw true try typeof var void while with yield let static implements interface package private protected public await".split(" "),
);

const camel = (s) => s.replace(/_+([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const param = (name) => {
  const c = camel(name);
  return RESERVED.has(c) ? `${c}_` : c;
};

if (!existsSync(manifestDir)) {
  console.error(`no manifests in ${manifestDir}; run \`make gen-ts\``);
  process.exit(1);
}
const manifests = readdirSync(manifestDir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((f) => JSON.parse(readFileSync(join(manifestDir, f), "utf8")));

// Export names: the Rust fn name in camelCase. Rust allows the same fn name in
// different modules; those get a suffix from their route so both stay usable.
const byName = new Map();
for (const m of manifests) {
  const name = camel(m.name);
  byName.set(name, [...(byName.get(name) ?? []), m]);
}
const renamed = [];
for (const [name, group] of byName) {
  for (const m of group) {
    if (group.length === 1) {
      m.exportName = name;
      continue;
    }
    const suffix = m.path
      .split("/")
      .filter((s) => s && !s.startsWith("{"))
      .map((s) => pascal(camel(s.replace(/-/g, "_"))))
      .join("");
    m.exportName = `${name}${m.method === "GET" ? "" : pascal(m.method.toLowerCase())}${suffix}`;
    renamed.push(`${m.method} ${m.path}: ${m.name} → ${m.exportName}`);
  }
}

const knownTypes = new Set(
  existsSync(typesDir) ? readdirSync(typesDir).filter((f) => f.endsWith(".ts") && f !== "index.ts").map((f) => f.slice(0, -3)) : [],
);
const missingTypes = new Map();
const unmapped = new Map();

function renderHandler(m) {
  const pathArgs = m.pathArgs.map((a) => ({ ...a, param: param(a.name) }));
  const query = m.queryArgs.map((a) => ({ ...a, param: param(a.name) }));
  const body = m.body ? { ...m.body, param: param(m.body.name) } : null;

  // Signature order: path args, required query args, body, optional query args.
  const sig = [
    ...pathArgs.map((a) => `${a.param}: ${a.ts}`),
    ...query.filter((a) => !a.optional).map((a) => `${a.param}: ${a.ts}`),
    ...(body ? [`${body.param}: ${body.ts}`] : []),
    ...query.filter((a) => a.optional).map((a) => `${a.param}?: ${a.ts}`),
  ];

  let path = m.path;
  for (const a of pathArgs) path = path.replace(`{${a.name}}`, `\${pathValue(${a.param})}`);

  const entry = (a) => (a.name === a.param ? a.name : `${a.name}: ${a.param}`);
  const queryObj = query.length ? `{ ${query.map(entry).join(", ")} }` : null;
  const bodyObj = body ? `{ ${entry(body)} }` : null;

  const fn = { GET: "apiGet", POST: "apiPost", PUT: "apiPut", PATCH: "apiPatch", DELETE: "apiDelete" }[m.method];
  const args =
    m.method === "GET"
      ? [queryObj]
      : m.method === "DELETE"
        ? [queryObj ?? (bodyObj ? "undefined" : null), bodyObj]
        : [bodyObj ?? (queryObj ? "undefined" : null), queryObj];
  while (args.length && args[args.length - 1] === null) args.pop();
  const call = [`\`${path}\``, ...args].join(", ");

  for (const t of m.refs) {
    if (!knownTypes.has(t)) missingTypes.set(t, [...(missingTypes.get(t) ?? []), m.exportName]);
  }
  for (const u of m.unmapped) unmapped.set(u, [...(unmapped.get(u) ?? []), m.exportName]);

  const runtime = ["pathValue", fn].filter((n) => n !== "pathValue" || pathArgs.length);
  const imports = [
    ...m.refs.map((t) => `import type { ${t} } from "../types/${t}";`),
    `import { ${runtime.sort().join(", ")} } from "../runtime/client";`,
  ];

  return `${HEADER}${imports.join("\n")}

/** \`${m.method} ${m.path}\` — Rust \`${m.name}\`. @throws ApiError */
export async function ${m.exportName}(${sig.join(", ")}): Promise<${m.returns}> {
  return ${fn}<${m.returns}>(${call});
}
`;
}

const outputs = new Map();
for (const m of manifests) outputs.set(join(handlersDir, `${m.exportName}.ts`), renderHandler(m));

const names = manifests.map((m) => m.exportName).sort();
outputs.set(
  join(pkg, "src/index.ts"),
  `${HEADER}
// Transport runtime (hand-written — owns fetch, Tauri transport, errors).
export { apiGet, apiPost, apiPut, apiPatch, apiDelete, ApiError, isTauri, pathValue, setBaseUrl, setHeaderProvider } from "./runtime/client";
export type { ServerError } from "./runtime/client";

// Generated typed API: one fn per Rust #[get]/#[post]/... handler.
${names.map((n) => `export { ${n} } from "./handlers/${n}";`).join("\n")}
`,
);

const drift = [];
const existing = existsSync(handlersDir) ? readdirSync(handlersDir).map((f) => join(handlersDir, f)) : [];
for (const [file, content] of outputs) {
  const current = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (current !== content) drift.push(`${current === null ? "missing" : "changed"}: ${file}`);
}
for (const file of existing) if (!outputs.has(file)) drift.push(`stale: ${file}`);

if (!check) {
  mkdirSync(handlersDir, { recursive: true });
  for (const [file, content] of outputs) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== content) writeFileSync(file, content);
  }
  for (const file of existing) if (!outputs.has(file)) rmSync(file);
}

console.log(`handlers: ${manifests.length}  renamed (duplicate fn names): ${renamed.length}  missing types: ${missingTypes.size}  unmapped Rust types: ${unmapped.size}`);
for (const r of renamed) console.log(`  renamed ${r}`);
for (const [u, users] of unmapped) console.log(`  unmapped ${u} (as unknown) in ${users.join(", ")}`);
if (missingTypes.size) console.log(`  missing types (need ts-rs export): ${[...missingTypes.keys()].sort().join(", ")}`);
console.log(check ? `out of date: ${drift.length}` : `updated: ${drift.length}`);
process.exit(check && drift.length ? 1 : 0);
