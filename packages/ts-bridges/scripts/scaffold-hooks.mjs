#!/usr/bin/env node
// ONE-TIME SCAFFOLD for the TanStack Query hooks in src/hooks/, ported from
// biyard/asset's server/scripts/scaffold-ts-hooks.mjs so both repos share the
// hook convention.
//
// This is NOT part of `make gen-ts`. The hooks it emits are committed as
// ordinary, HAND-MAINTAINED source: `make gen-ts` only regenerates
// src/handlers and src/types, so src/hooks survives untouched. When a new
// handler is added, add its hook by hand (or re-run with --only <handler> and
// review the diff).
//
// For each generated handler in src/handlers/*.ts it emits src/hooks/<useX>.ts:
//   - apiGet handler            -> useX(...args, options?) wrapping useQuery,
//                                  query key ["<x>", ...args]
//   - apiPost/Put/Patch/Delete  -> useX(options?) wrapping useMutation
// and rewrites src/hooks/index.ts to re-export every file in src/hooks.
// Existing hook files are kept unless --force is passed.
//
// Usage: node scaffold-hooks.mjs [--force] [--only <handlerName> ...]
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(pkg, "src");
const handlersDir = join(srcDir, "handlers");
const hooksDir = join(srcDir, "hooks");
const typesDir = join(srcDir, "types");

const argv = process.argv.slice(2);
const force = argv.includes("--force");
const onlyIdx = argv.indexOf("--only");
const only = onlyIdx >= 0 ? new Set(argv.slice(onlyIdx + 1)) : null;

mkdirSync(hooksDir, { recursive: true });

const typeFiles = new Set(
  existsSync(typesDir)
    ? readdirSync(typesDir).filter((f) => f.endsWith(".ts") && f !== "index.ts").map((f) => f.slice(0, -3))
    : [],
);

const HEADER =
  "// HAND-MAINTAINED TanStack Query hook. Scaffolded by scaffold-hooks.mjs.\n" +
  "// NOT regenerated by `make gen-ts`; edit freely. See the scaffold script header.\n";

/** Split a parameter list on top-level commas (depth-aware for <>, {}, ()). */
function splitParams(s) {
  const out = [];
  let depth = 0;
  let cur = "";
  for (const ch of s) {
    if (ch === "<" || ch === "{" || ch === "(") depth++;
    else if (ch === ">" || ch === "}" || ch === ")") depth--;
    if (ch === "," && depth === 0) {
      out.push(cur.trim());
      cur = "";
    } else cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

/** Bare type identifiers referenced by a TS type string that live in types/. */
function referencedTypes(typeStr) {
  const ids = typeStr.match(/[A-Z][A-Za-z0-9_]*/g) || [];
  return [...new Set(ids)].filter((id) => typeFiles.has(id));
}

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

const stems = readdirSync(handlersDir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .map((f) => f.slice(0, -3))
  .sort();

let written = 0;
let kept = 0;
for (const stem of stems) {
  if (only && !only.has(stem)) continue;
  const src = readFileSync(join(handlersDir, `${stem}.ts`), "utf8");
  const m = src.match(/export async function (\w+)\(([\s\S]*?)\):\s*Promise<[\s\S]*?>\s*\{/);
  if (!m) {
    console.warn(`skip ${stem}: no parseable signature`);
    continue;
  }
  const fnName = m[1];
  const params = splitParams(m[2]).map((p) => {
    const idx = p.indexOf(":");
    const rawName = p.slice(0, idx).trim();
    return { name: rawName.replace(/\?$/, ""), optional: rawName.endsWith("?"), type: p.slice(idx + 1).trim() };
  });

  const isQuery = /\bapiGet\b/.test(src);
  const base = fnName.replace(/Handler$/, "");
  const hookName = "use" + cap(base);
  const file = join(hooksDir, `${hookName}.ts`);
  if (existsSync(file) && !force) {
    kept++;
    continue;
  }

  const imports = new Set();
  for (const p of params) for (const t of referencedTypes(p.type)) imports.add(t);
  const importLines = [...imports]
    .sort()
    .map((t) => `import type { ${t} } from "../types/${t}";`)
    .join("\n");
  const decl = (p) => `${p.name}${p.optional ? "?" : ""}: ${p.type}`;

  let body;
  if (isQuery) {
    const optsParam = 'options?: Omit<UseQueryOptions<Data, ApiError>, "queryKey" | "queryFn">';
    const sig = [...params.map(decl), optsParam].join(",\n  ");
    const names = params.map((p) => p.name);
    const key = names.length ? `["${base}", ${names.join(", ")}]` : `["${base}"]`;
    body = `${HEADER}import { useQuery, type UseQueryOptions } from "@tanstack/react-query";
import { ${fnName} } from "../handlers/${fnName}";
import type { ApiError } from "../runtime/client";${importLines ? "\n" + importLines : ""}

type Data = Awaited<ReturnType<typeof ${fnName}>>;

export function ${hookName}(
  ${sig},
) {
  return useQuery<Data, ApiError>({
    queryKey: ${key},
    queryFn: () => ${fnName}(${names.join(", ")}),
    ...options,
  });
}
`;
  } else {
    let varsType, callExpr;
    if (params.length === 0) {
      varsType = "void";
      callExpr = `() => ${fnName}()`;
    } else if (params.length === 1 && !params[0].optional) {
      varsType = params[0].type;
      callExpr = `(vars) => ${fnName}(vars)`;
    } else {
      varsType = "{ " + params.map(decl).join("; ") + " }";
      callExpr = `(vars) => ${fnName}(${params.map((p) => `vars.${p.name}`).join(", ")})`;
    }
    body = `${HEADER}import { useMutation, type UseMutationOptions } from "@tanstack/react-query";
import { ${fnName} } from "../handlers/${fnName}";
import type { ApiError } from "../runtime/client";${importLines ? "\n" + importLines : ""}

type Data = Awaited<ReturnType<typeof ${fnName}>>;
type Vars = ${varsType};

export function ${hookName}(
  options?: Omit<UseMutationOptions<Data, ApiError, Vars>, "mutationFn">,
) {
  return useMutation<Data, ApiError, Vars>({
    mutationFn: ${callExpr},
    ...options,
  });
}
`;
  }
  writeFileSync(file, body);
  written++;
}

const hookFiles = readdirSync(hooksDir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .map((f) => f.slice(0, -3))
  .sort();
writeFileSync(
  join(hooksDir, "index.ts"),
  "// HAND-MAINTAINED barrel for TanStack Query hooks (scaffolded; edit freely).\n" +
    hookFiles.map((h) => `export * from "./${h}";`).join("\n") +
    "\n",
);

console.log(`hooks: ${written} written, ${kept} kept, ${hookFiles.length} in index`);
